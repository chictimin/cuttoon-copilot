// 말풍선 칸(position)별 자리 비율 — Export(compose.ts)와 에디터 미리보기(#278)가 같은 값을 쓰도록
// 여기 한 곳에만 둔다. 클라이언트 컴포넌트도 import하므로 런타임 import를 두지 않는다
// (compose.ts는 sharp를 불러서 브라우저 번들에 넣을 수 없다).
//
// 값은 캔버스 비율(0~1)의 **초기 배치값**이다: x·w는 글자 상자의 가로 위치·폭, y는 글자 상자 윗변.
// 긴 대사는 y에서 아래로 자란다. 실제 몸통 위치는 compose.ts의 보정 뒤라 이 값과 다를 수 있다
// (#279 리뷰) — rounded 타원은 상자보다 위아래로 커서 윗변이 y보다 위에 오고, 캔버스를 넘치면
// 좌우·위(rounded)·아래(bottom 칸) 경계 보정이 옮기며, center는 줄이 많으면 폭을 넓힌다.
// 에디터 미리보기(#278)는 이 초기 배치값으로 "어느 높이대인지"만 맞춘다.

import type { Position } from "./types";

export interface PositionBox {
  x: number;
  y: number;
  w: number;
}

// 구석 자리는 일부러 캔버스 경계를 살짝 넘어가게 뒀다 — 인선님 피드백(2026-08-19):
// "화면을 나가도 된다, 그림에 반 걸치고 화면 밖으로 반 걸치고" — 실제 웹툰에서 흔히
// 쓰는 방식이고, 인물(보통 화면 중앙 쪽)에서 멀어지니 얼굴을 덜 가리는 효과도 같이 있다.
// composeCut의 SVG 오버레이가 캔버스 크기 그대로라 경계 밖으로 나간 부분은 자동으로 잘린다.
// (말풍선 도형 자체는 텍스트 박스보다 위아래로 28% 더 커서, 이 값이 0이어도 이미
// 타원 테두리가 살짝 넘어간다 — 텍스트는 안전하게 안쪽에 두면서 도형만 자연스럽게
// 걸치게 하려고 오프셋을 크게 잡지 않았다.)
// bottom_* 는 아래쪽 구석에 두되, 인선님 피드백("꼬리만 가지 말고 말풍선 전체를
// 당겨줘")에 따라 예전(y: 0.66)보다 인물 쪽(화면 중앙)에 확실히 더 가깝게 뒀다.
// top_* 도 같은 이유로 예전(y: 0.0, 캔버스 맨 위)보다 인물(보통 화면 중앙 쪽) 쪽으로
// 당겼다(인선님 피드백 2026-08-20: "사람하고 가깝게 그려줘").
// #259-8 D(2026-10-07): bottom_* 0.46은 인물 얼굴 높이(세로 25~60%)와 겹쳐 말풍선이 얼굴을
// 덮었다(저장 컷 32개 중 bottom 15개). 그림이 아래를 비우는 경우(reserved_zone: bottom)에
// 그 비운 자리로 가도록 0.70으로 내린다. 긴 대사는 아래 경계 보정이 위로 올린다.
export const POSITION_BOX: Record<Position, PositionBox> = {
  top_left: { x: -0.03, y: 0.07, w: 0.44 },
  top_right: { x: 0.59, y: 0.07, w: 0.44 },
  bottom_left: { x: 0.0, y: 0.7, w: 0.44 },
  bottom_right: { x: 0.56, y: 0.7, w: 0.44 },
  center: { x: 0.22, y: 0.38, w: 0.56 },
};
